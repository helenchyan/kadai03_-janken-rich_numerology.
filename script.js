// 生年月日をプルダウンから選択できるようにした。今年から1930年まで。
// 年が変わっても最新の年から選べるようにした。
//constは変わらないもの、書き換えられないもの。letは書き換えられるもの。全部letでも動くがエラーが分かりにくくなる
const thisYear = new Date().getFullYear();
for (let y = thisYear; y >= 1930; y--) {
  $(".input-year").append("<option>" + y + "</option>"); //ここの＋は文字列の合体として認識させるためのもの
}
$(".input-year").val(thisYear - 35); //使用者の歳の中央値を35歳と仮定してスクロールのストレスを軽減

//まずは年月日を数字として認識させる
$(".button").on("click", function () {
  const y = Number($(".input-year").val());
  const m = Number($(".input-month").val());
  const d = Number($(".input-day").val());
  console.log("y =", y, "m =", m, "d=", d);

  //年の各位の数字を足す
  //Math.floorは小数点以下の切り捨て
  //%10は10で割ったときの余り。10で割った場合は1の位の数字になるので、1の位を取り出せる
  const y1 = Math.floor(y / 1000);
  const y2 = Math.floor(y / 100) % 10;
  const y3 = Math.floor(y / 10) % 10;
  const y4 = y % 10;
  const yearSum = y1 + y2 + y3 + y4; //CSSは - でつなぐ（news-item）、JSは2単語目以降を大文字でつなぐ（yearSum）のが慣習らしい
  console.log("年の各位の合計=", yearSum);

  //月の各位の数字を足す
  const m1 = Math.floor(m / 10);
  const m2 = m % 10;
  const monthSum = m1 + m2;
  console.log("月の各位の合計=", monthSum);

  //日の各位の数字を足す
  const d1 = Math.floor(d / 10);
  const d2 = d % 10;
  const daySum = d1 + d2;
  console.log("日の各位の合計=", daySum);

  //年と月と日の各位の合算
  const birthSum = yearSum + monthSum + daySum;
  console.log("年月日の各位の合算=", birthSum);

  //年月日の各位の合算を一桁になるまで足す＝太陽数を出す
  //例えばbirthSumが48の場合、1回目の還元では12になりもう1回必要となるので2回繰り返している
  //2回目の還元を有効にするため、constではなくletを使う
  let sun = birthSum;
  //a !== b	a と b が等しくない（型も含めて厳密に）
  // a && b	a も b も true のとき true（かつ）
  // a || b	a か b のどちらかが true なら true（または）
  if (sun !== 11 && sun !== 22 && sun !== 33) {
    sun = Math.floor(sun / 10) + (sun % 10);
  }
  if (sun !== 11 && sun !== 22 && sun !== 33) {
    sun = Math.floor(sun / 10) + (sun % 10);
  }

//【別の書き方メモ】while を使うと桁数を決め打ちしなくて済む（教程3で習う）
//
//   let n = y;
//   let yearSum = 0;
//   while (n > 0) {
//     yearSum += n % 10;        // 一の位を足す
//     n = Math.floor(n / 10);   // 一の位を落とす
//   }
//
// ・while (条件) { } ＝ 条件が true のあいだ、{ } を繰り返す
// ・yearSum = 0 の「0」は必須。一の位を足すところで、この0足す形で指示をだしているから起点がなくなる
//   let yearSum; だけだと中身が undefined で、undefined + 5 → NaN になる
//   空の状態から始める。数の合計なら 0、文字列をつなぐなら ""
// ・+= で書き換えるので const ではなく let
// ・いまの4行版（y1〜y4）が const でよいのは、1回計算して終わりだから
// ・この形は年・月・日・太陽数の還元すべてで同じ。
//   同じ処理を1か所にまとめる方法が「関数」で、教程4（11/25）で習う

//各数字の説明文を出す
  console.log("太陽数=", sun);
  $(".result-number").html(sun);
  $(".result-number").attr("class", "result-number num-" + sun);
  $(".meaning").hide();
  $(".meaning-" + sun).show();
});


